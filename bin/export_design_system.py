def _block(css: str, selector: str) -> str:
    """Return the body of the first `selector { … }` block in ``css``.

    Args:
        css: The stylesheet source.
        selector: Literal selector text to find, e.g. ``[data-wine="rose"]``.

    Returns:
        Everything between the braces, comments and all.

    Raises:
        SystemExit: If the block is missing — that means main.css was
            restructured, and silently exporting an empty palette would be far
            worse than stopping.

    """
    start = css.find(selector + " {")
    if start < 0:
        raise SystemExit(f"{SOURCE}: no `{selector}` block — has it been renamed?")
    open_brace = css.index("{", start)
    depth, i = 0, open_brace
    while i < len(css):
        if css[i] == "{":
            depth += 1
        elif css[i] == "}":
            depth -= 1
            if depth == 0:
                return css[open_brace + 1 : i]
        i += 1
    raise SystemExit(f"{SOURCE}: `{selector}` block is not closed")


def build_stylesheet() -> str:
    """Build the plain-CSS token sheet from main.css.

    The app's copy is a Tailwind v4 `@theme static` block, which only means
    anything inside a Tailwind build. The preview cards are standalone HTML,
    so the same declarations are re-emitted under `:root`. Everything else —
    the per-wine themes, the dark overrides — is already plain CSS and is
    copied verbatim.
    """
    css = SOURCE.read_text(encoding="utf-8")
    parts = [
        "/*\n"
        " * Wineguide — design tokens, as built.\n"
        " *\n"
        " * GENERATED by bin/export_design_system.py from src/css/main.css,\n"
        " * which is the single source. Do not edit: edit main.css and re-run.\n"
        " *\n"
        " * The app's copy is a Tailwind `@theme static` block; this is the\n"
        " * same declarations as plain custom properties so the preview cards\n"
        " * can use them without a build step.\n"
        " */\n",
        ":root {" + _block(css, "@theme static") + "}\n",
    ]

    for code, _label in WINES:
        selector = f'[data-wine="{code}"]'
        parts.append(selector + " {" + _block(css, selector) + "}\n")

    parts.append("[data-wine] {" + _block(css, "[data-wine]") + "}\n")
    parts.append(
        ':root[data-theme="dark"], [data-theme="dark"] {'
        + _block(css, ':root[data-theme="dark"]')
        + "}\n"
    )
    # The app scopes this under :root; the cards set data-theme on a div, so
    # it is widened to any ancestor.
    parts.append(
        '[data-theme="dark"] [data-wine], [data-wine][data-theme="dark"] {\n'
        "  --color-accent: var(--accent-dark);\n"
        "  --color-accent-quiet: var(--accent-quiet-dark);\n"
        "}\n"
    )
    parts.append(CARD_CHROME)
    return "\n".join(parts)


def card(
    path: str, group: str, viewport: str, name: str, subtitle: str, body: str
) -> None:
    """Write one preview card.

    The `@dsCard` comment must be the very first line — the Design System pane
    builds its index from it — and the charset declaration must come before any
    text, or every em-dash and ellipsis in the subtitles renders as mojibake.
    """
    target = OUT / path
    target.parent.mkdir(parents=True, exist_ok=True)
    depth = path.count("/")
    target.write_text(
        f'<!-- @dsCard group="{group}" viewport="{viewport}" name="{name}" '
        f'subtitle="{subtitle}" -->\n'
        '<meta charset="utf-8">\n'
        f'<link rel="stylesheet" href="{"../" * depth}styles.css">\n'
        f"{body.strip()}\n",
        encoding="utf-8",
    )


def swatch(var: str, label: str) -> str:
    """Return a labelled colour chip."""
    return (
        '<div style="display:flex;flex-direction:column;gap:6px">'
        f'<span style="display:block;width:96px;height:48px;'
        f"border-radius:var(--radius-control);background:var(--{var});"
        f'border:1px solid var(--color-rule)"></span>'
        f'<span class="lbl">{label}</span></div>'
    )


def dots(
    total: int = 20,
    answered: int = 6,
    current: int = 6,
    rung: int = 3,
    breaks: tuple[int, ...] = (3, 8, 16),
) -> str:
    """Return the progress rail — answered solid, current ringed, rest outlined."""
    out = []
    for i in range(total):
        if i in breaks:
            out.append(
                '<span style="display:inline-block;width:1px;height:10px;'
                'background:var(--color-rule-strong);margin:0 5px"></span>'
            )
        if i < answered:
            style = f"background:var(--color-depth-{rung});border:1px solid transparent"
        elif i == current:
            style = f"background:transparent;border:2px solid var(--color-depth-{rung})"
        else:
            style = "background:transparent;border:1px solid var(--color-rule-strong)"
        out.append(
            '<span style="box-sizing:border-box;display:inline-block;width:10px;'
            f'height:10px;border-radius:999px;margin:0 2px;{style}"></span>'
        )
    return "".join(out)


def option(
    label: str, desc: str, *, selected: bool = False, rung: int | None = None
) -> str:
    """Return one option row — 76px minimum, selected is a fill plus accent border."""
    border = "var(--color-accent)" if selected else "var(--color-rule)"
    bg = "var(--color-paper-raised)" if selected else "var(--color-paper-sunken)"
    disc = (
        f'<span style="width:40px;height:40px;flex:none;border-radius:999px;'
        f'background:var(--color-depth-{rung})"></span>'
        if rung
        else ""
    )
    return (
        f'<div style="display:flex;align-items:center;gap:14px;min-height:76px;'
        f"padding:12px 16px;background:{bg};border:1px solid {border};"
        f'border-radius:var(--radius-card)">{disc}'
        '<span style="display:flex;flex-direction:column;gap:2px">'
        f'<span style="font-family:var(--font-serif);font-size:var(--text-answer)">{label}</span>'
        f'<span style="font-family:var(--font-sans);font-size:var(--text-fact);'
        f'color:var(--color-ink-muted)">{desc}</span></span></div>'
    )


