def main() -> None:
    """Rebuild `design-export/` from scratch."""
    if OUT.exists():
        # Rebuilt whole rather than merged: a card renamed or dropped in this
        # script must not linger on disk and get pushed as if it were current.
        shutil.rmtree(OUT)
    OUT.mkdir(parents=True)

    (OUT / "styles.css").write_text(build_stylesheet(), encoding="utf-8")
    write_foundations()
    write_components()

    written = sorted(
        p.relative_to(OUT).as_posix() for p in OUT.rglob("*") if p.is_file()
    )
    for path in written:
        print(path)  # noqa: T201 — this script's whole output is its file list
    print(f"\n{len(written)} files → {OUT.relative_to(ROOT)}")  # noqa: T201


if __name__ == "__main__":
    main()
