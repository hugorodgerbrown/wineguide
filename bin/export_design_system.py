"""
bin/export_design_system.py — Build the Claude Design bundle for this app.

Regenerates `design-export/`: a `styles.css` plus one preview card per
foundation and component, each carrying the `@dsCard` marker the Design System
pane indexes on. Push it with the DesignSync MCP:

    python bin/export_design_system.py
    # then, via DesignSync: finalize_plan → write_files from design-export/

The output is a build artefact and is gitignored, exactly like
`static/css/output.css`. What is versioned is this script, so the export is
reproducible from `src/css/main.css` rather than being a snapshot somebody
took once by hand.

**The tokens are read out of `src/css/main.css`, never retyped.** That file is
the single source; a second copy of the palette in this script would be wrong
within a month and nothing would catch it. The parsing is deliberately literal
— it lifts whole blocks and rewrites only the `@theme static` wrapper — so a
token added upstream appears here without anyone touching this file.

Target project: "Wineguide — as built"
(8019a23f-e49f-43dc-8714-fe5ebb8583d4). The source design directions live in a
different project, which this must never write to — that one is the brief,
this one is what got built.
"""

